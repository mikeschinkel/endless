"""Go support for task worktrees (E-2563): a worktree extension, not core.

Go finds a `go.work` by walking up from the current directory, and a task
worktree lives inside its main checkout (`.endless/worktrees/e-NNN/`). So a
`go.work` in the main checkout is found from the worktree, and Go then
refuses to build there, because the worktree's modules are not the ones that
file lists:

    pattern ./...: directory prefix . does not contain modules listed in
    go.work or their selected dependencies

The nearest `go.work` wins, so one in the worktree itself shields it. This
extension writes that file: a `go.work` that lists every module in the
worktree — nested `test/` and `examples/` modules included — and nothing
outside it, so the worktree builds against published versions of everything
else. It is written in every Go worktree, not only under a main checkout
that has a `go.work` today, so a `go.work` added to the main checkout later
needs no further step.

What it does not do:

- touch a worktree that already has a `go.work`, whether tracked in the
  repository or generated by the project's own post-worktree-create hook;
- point at sibling worktrees or sibling checkouts;
- change a main checkout's `go.work`;
- write `.git/info/exclude`. A repository whose `.gitignore` does not cover
  `go.work` gets a warning to add it, because a hidden exclude would leave
  its owner unaware that the entry is missing.

Detection is by `go.mod`, not by `projects.language`, which is unreliable
(it lists Endless itself as bash, and many projects leave it empty).

This module is built into Endless but stays outside its core, behind the
`worktree_ext` extension point, so it can later move to Gomion or call it.
"""

from __future__ import annotations

import os
import shutil
import subprocess
from pathlib import Path

import click

from endless import agent_help, config, worktree_ext

EXTENSION_NAME = "go-support"

GO_MOD = "go.mod"
GO_WORK = "go.work"
GO_WORK_SUM = "go.work.sum"

# Directories a module search never enters. `.endless/` holds the sandbox and
# scratch, `vendor/` holds copies of other people's modules, and `testdata/`
# holds fixtures that are modules on purpose. `.git` is a file in a worktree,
# but a directory in a checkout, and is never a module either way.
PRUNED_DIRS: frozenset[str] = frozenset({"vendor", "testdata", ".git", ".endless"})


def go_modules(worktree: Path) -> list[Path]:
    """The directories under `worktree` that hold a `go.mod`, as paths
    relative to the worktree, sorted, with the pruned directories skipped."""
    found: list[Path] = []
    for dirpath, dirnames, filenames in os.walk(worktree):
        dirnames[:] = sorted(d for d in dirnames if d not in PRUNED_DIRS)
        if GO_MOD in filenames:
            found.append(Path(dirpath).relative_to(worktree))
    return sorted(found)


def ensure_go_work(worktree: Path) -> bool:
    """Write `go.work` into `worktree` when it is a Go worktree without one.

    Returns True when the file was written. Does nothing for a worktree with
    no module and nothing for one that already has a `go.work`, which is
    what makes it safe to run at every session start.
    """
    modules = go_modules(worktree)
    if not modules:
        return False
    if (worktree / GO_WORK).exists():
        return False

    go = shutil.which("go")
    if go is None:
        raise RuntimeError(
            f"{config.tilde(worktree)} holds a Go module but `go` is not on PATH, "
            f"so no go.work was written"
        )
    # The resolved path, with symlinks followed, for both the working
    # directory and GOWORK. `go work use` writes each module relative to the
    # go.work's directory, computed from the directory the OS reports, and
    # when the two spellings differ (`/var/...` vs `/private/var/...` on
    # macOS) it writes paths that climb out through the symlink, which Go
    # then refuses to match against the directory a build runs in.
    real = worktree.resolve()
    go_work = real / GO_WORK
    # GOWORK pinned to the file being written: without it `go work init`
    # finds the main checkout's go.work by walking up and refuses ("already
    # exists"), and `go work use` would then edit THAT file.
    env = {**os.environ, "GOWORK": str(go_work), "PWD": str(real)}
    _go(go, ["work", "init"], real, env)
    _go(go, ["work", "use", *(_use_arg(m) for m in modules)], real, env)

    agent_help.info(
        click.style("•", fg="cyan")
        + f" wrote {GO_WORK} for {config.tilde(worktree)} "
        + f"({len(modules)} module{'s' if len(modules) != 1 else ''})",
        err=True,
    )
    if gitignore_covers(worktree, GO_WORK, GO_WORK_SUM) is False:
        _warn_not_ignored(worktree)
    return True


def _use_arg(module: Path) -> str:
    # `go work use` wants a path, and `.` for the root; a bare relative path
    # like `test` works too but `./test` is what `go work use` itself writes.
    return "." if module == Path(".") else f"./{module.as_posix()}"


def _go(go: str, args: list[str], cwd: Path, env: dict[str, str]) -> None:
    result = subprocess.run(
        [go, *args], cwd=str(cwd), env=env, capture_output=True, text=True,
    )
    if result.returncode != 0:
        detail = (result.stderr or result.stdout).strip()
        raise RuntimeError(f"`go {' '.join(args)}` exited {result.returncode}: {detail}")


def gitignore_covers(worktree: Path, *names: str) -> bool | None:
    """Whether every one of `names` is ignored by a `.gitignore` in the
    repository — not by `.git/info/exclude` and not by the user's global
    excludes file, which cover only this clone and this machine.

    None when git could not answer (not a repository, or git is missing),
    which is not a verdict either way.
    """
    try:
        result = subprocess.run(
            ["git", "check-ignore", "-v", "--", *names],
            cwd=str(worktree), capture_output=True, text=True,
        )
    except OSError:
        return None
    # 0: at least one path is ignored; 1: none is; anything else is an error.
    if result.returncode not in (0, 1):
        return None
    covered: set[str] = set()
    for line in result.stdout.splitlines():
        # `<source>:<linenum>:<pattern>\t<pathname>`. A negated pattern is
        # printed too, and means the path is NOT ignored.
        head, sep, path = line.rpartition("\t")
        if not sep:
            continue
        source, _, pattern = head.split(":", 2)
        if pattern.startswith("!"):
            continue
        # A relative source is a file in the repository; an absolute one is
        # the global excludes file (which may itself be named .gitignore).
        if source.startswith("/") or Path(source).name != ".gitignore":
            continue
        covered.add(path)
    return all(name in covered for name in names)


def _warn_not_ignored(worktree: Path) -> None:
    where = config.tilde(worktree)
    # NO-REPORT: the fix is two lines in a tracked file, and it is the agent's
    # to make on its branch — the repository is missing an entry every Go
    # workspace needs, and the next task to touch it is the one that adds it.
    agent_help.warn.no_report(
        f"{where}/{GO_WORK} was written, but the repository's .gitignore does "
        f"not cover {GO_WORK} and {GO_WORK_SUM}, so git will show them as "
        f"untracked.",
        f"Add {GO_WORK} and {GO_WORK_SUM} to the repository's .gitignore on "
        f"your branch; Endless never writes .git/info/exclude for them",
        text=(
            click.style(f"⚠ {GO_WORK} is not in .gitignore", fg="yellow")
            + f"\n    Endless wrote {where}/{GO_WORK} for this worktree, and git\n"
            f"    will list it as untracked. Add these two lines to the\n"
            f"    repository's .gitignore:\n"
            f"        {GO_WORK}\n"
            f"        {GO_WORK_SUM}"
        ),
    )


worktree_ext.register(EXTENSION_NAME, ensure_go_work)
